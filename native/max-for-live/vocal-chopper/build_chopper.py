DIVS = [("1/1", "1n"), ("1/2", "2n"), ("1/4", "4n"), ("1/8", "8n"), ("1/16", "16n"), ("1/32", "32n"), ("1/8T", "8nt"), ("1/16T", "16nt")]

def build_chopper(code):
    p = Patch()
    # ---- gen~ (embedded patcher with one codebox)
    gin = [dict(id=f"obj-{i}", maxclass="newobj", text=f"in {i}", numinlets=0, numoutlets=1, outlettype=[""],
                patching_rect=[30.0 + 80 * (i - 1), 30.0, 40.0, 22.0]) for i in (1, 2)]
    gcode = dict(id="obj-3", maxclass="codebox", code=code, numinlets=2, numoutlets=8, outlettype=[""] * 8,
                 patching_rect=[30.0, 80.0, 760.0, 600.0], fontname="Menlo", fontsize=11.0)
    gout = [dict(id=f"obj-{3 + i}", maxclass="newobj", text=f"out {i}", numinlets=1, numoutlets=0,
                 patching_rect=[30.0 + 80 * (i - 1), 720.0, 40.0, 22.0]) for i in range(1, 9)]
    gboxes = [{"box": b} for b in gin + [gcode] + gout]
    glines = []
    for i in range(2):
        glines.append({"patchline": {"destination": ["obj-3", i], "source": [f"obj-{i + 1}", 0]}})
    for i in range(8):
        glines.append({"patchline": {"destination": [f"obj-{4 + i}", 0], "source": ["obj-3", i]}})
    gen_patcher = {"fileversion": 1, "appversion": {"major": 8, "minor": 6, "revision": 2, "architecture": "x64", "modernui": 1},
                   "classnamespace": "dsp.gen", "rect": [100.0, 100.0, 840.0, 780.0], "bglocked": 0, "openinpresentation": 0,
                   "default_fontsize": 12.0, "default_fontface": 0, "default_fontname": "Arial", "gridonopen": 1,
                   "gridsize": [15.0, 15.0], "gridsnaponopen": 1, "objectsnaponopen": 1, "statusbarvisible": 2,
                   "toolbarvisible": 1, "lefttoolbarpinned": 0, "toptoolbarpinned": 0, "righttoolbarpinned": 0,
                   "bottomtoolbarpinned": 0, "toolbars_unpinned_last_save": 0, "tallnewobj": 0, "boxanimatetime": 200,
                   "enablehscroll": 1, "enablevscroll": 1, "devicewidth": 0.0, "description": "", "digest": "", "tags": "",
                   "style": "", "subpatcher_template": "", "assistshowspatchername": 0, "boxes": gboxes, "lines": glines}

    plugin = p.obj("plugin~", 2, 2, ["signal", "signal"])
    gen = p.add(maxclass="newobj", text="gen~", numinlets=2, numoutlets=8, outlettype=["signal"] * 8, patcher=gen_patcher)
    plugout = p.obj("plugout~", 2, 0)
    for i in range(2):
        p.line(plugin, i, gen, i)
        p.line(gen, i, plugout, i)
    names = ["mmmv1L", "mmmv1R", "mmmv2L", "mmmv2R", "mmmv3L", "mmmv3R", "mmmv4L", "mmmv4R"]
    for i, nm in enumerate(names):
        s = p.obj(f"send~ {nm}", 1, 0)
        p.line(gen, i, s, 0)

    def to_gen(src, srcout, name, extra=None):
        pp = p.obj(f"prepend {name}", 1, 1)
        p.line(src, srcout, pp, 0)
        if extra:
            pass
