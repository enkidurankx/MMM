def build_chopout():
    p = Patch()
    plugin = p.obj("plugin~", 2, 2, ["signal", "signal"])
    plugout = p.obj("plugout~", 2, 0)
    tab = p.enum("live.tab", "Voice", "Voice", ["1", "2", "3", "4"], 1, [6, 6, 120, 20])
    dry = p.dial(("dry", "Dry", "Dry", 0, 1, 0, 1, 0, 1.0), [134, 4, 46, 48])
    lvl = p.dial(("lvl", "Level", "Level", 0, 1.5, 1, 1, 0, 1.0), [186, 4, 46, 48])
    p.comment("MMM CHOP OUT", [6, 32, 120, 14], size=10.0, bold=1)
    p.comment("voice from the chopper", [6, 48, 126, 12], size=8.0)
    plus = p.obj("+ 1", 2, 1)
    p.line(tab, 0, plus, 0)
    dl, ll = [], []
    for side, pin in (("L", 0), ("R", 1)):
        sp = p.obj(f"sprintf set mmmv%d{side}", 1, 1)
        p.line(plus, 0, sp, 0)
        rc = p.obj(f"receive~ mmmv2{side}", 1, 1, ["signal"])
        p.line(sp, 0, rc, 0)
        gl = p.obj("*~ 1.", 2, 1, ["signal"])      # level
        gd = p.obj("*~ 0.", 2, 1, ["signal"])      # dry
        su = p.obj("+~", 2, 1, ["signal"])
        p.line(rc, 0, gl, 0)
        p.line(plugin, pin, gd, 0)
        p.line(gl, 0, su, 0)
        p.line(gd, 0, su, 1)
        p.line(su, 0, plugout, pin)
        dl.append(gd)
        ll.append(gl)
    for dial_, gains, nm in ((dry, dl, "dry"), (lvl, ll, "lvl")):
        pk = p.obj("pak 0. 20", 2, 1)
        ln = p.obj("line~", 2, 1, ["signal"])
        p.line(dial_, 0, pk, 0)
        p.line(pk, 0, ln, 0)
        for g in gains:
            p.line(ln, 0, g, 1)
    return finish(p.boxes, p.lines, 240.0, "MMM Chop Out: receives one voice of the MMM Vocal Chopper (put one per rack chain)")


def write(doc, base):
    with open(base + ".maxpat", "w") as f:
        f.write(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    with open(base + ".amxd", "wb") as f:
        f.write(amxd_bytes(doc))

