#!/usr/bin/env python3
"""Generates the MMM Vocal Chopper devices (Max for Live, audio effects).

  python3 build_chopper.py  ->  MMM_VocalChopper.genexpr  (the engine, paste-able into any gen~ codebox)
                                MMM_VocalChopper.maxpat / .amxd   (the chopper: gen~ + live.* UI, 4 outs via send~)
                                MMM_ChopOut.maxpat / .amxd        (tiny receiver: put one per rack chain)

Why two devices: a Max for Live audio effect has exactly one stereo output. The chopper therefore renders FOUR voices
(= 4 stereo outs), plays voice 1 on its own output and ALSO publishes all four with send~ (mmmv1L ... mmmv4R). Drop the
chopper into chain 1 of an Audio Effect Rack and a "MMM Chop Out" into chains 2-4 (voice 2/3/4): every chain gets its own
effects after it.

GenExpr style follows what is proven to run in Live in ../../age12/m4l (Param / History / Data / peek / poke / floor /
min / max / pow / exp / log / cos / noise, plain if-blocks, every local initialised at the top, no loops, no ternary).
The grain pool is unrolled by this script instead of using Data arrays + for loops.
"""
import json, os, struct, sys

NG = 8            # grain pool size
BUF = 768000      # samples per channel (8 s @ 96 kHz)

# --------------------------------------------------------------------------- parameters
# (msg name, longname, short, min, max, init, unitstyle, type 0 float / 1 int, exponent)
# unitstyle: 0 int, 1 float, 2 ms, 3 Hz, 4 dB, 7 semitones
DIALS = {
    "simple": [
        ("rateHz",   "Rate Hz",    "Rate",   0.2,  30,   4,    3, 0, 2.0),   # free clock; goes to the ms metro, not to gen~
        ("p_chaos",  "Chaos",      "Chaos",  0,    1,    0.5,  1, 0, 1.0),
        ("p_size",   "Size",       "Size",   10,   2000, 150,  2, 0, 3.0),
        ("p_prob",   "Probability", "Prob",  0,    1,    1,    1, 0, 1.0),
        ("p_thr",    "Onset Threshold", "Thresh", -60, 0, -30, 4, 0, 1.0),
        ("p_dry",    "Dry",        "Dry",    0,    1,    0,    1, 0, 1.0),
    ],
    "mangle": [
        ("p_range",  "Range",      "Range",  0.02, 1,    0.6,  1, 0, 1.0),
        ("p_pitch",  "Pitch Scatter", "Pitch", 0,  24,   7,    7, 1, 1.0),
        ("p_rev",    "Reverse",    "Rev",    0,    1,    0.3,  1, 0, 1.0),
        ("p_rept",   "Repeats",    "Repeat", 1,    8,    1,    0, 1, 1.0),
        ("p_width",  "Width",      "Width",  0,    1,    0.6,  1, 0, 1.0),
        ("p_fade",   "Fade",       "Fade",   1,    100,  5,    2, 0, 2.0),
        ("p_lvlvar", "Level Variation", "LvlVar", 0, 1,  0.5,  1, 0, 1.0),
        ("p_bufsec", "Buffer Seconds", "Buffer", 0.5, 8, 4,    1, 0, 1.0),
        ("p_sens",   "Onset Sensitivity", "Sens", 1.2, 6, 2,   1, 0, 1.0),
        ("p_gap",    "Onset Gap",  "Gap",    10,   500,  60,   2, 0, 2.0),
    ],
    "lfo": [
        ("p_lfor",     "LFO Rate",  "LFO Rate", 0.05, 20,   2,   3, 0, 2.0),
        ("p_lfoslew",  "LFO Slew",  "Slew",     0,    2000, 50,  2, 0, 3.0),
        ("p_lfodepth", "LFO Depth", "Depth",    0,    1,    0.5, 1, 0, 1.0),
    ],
}
LFO_TARGETS = [("p_tsize", "Size", 1), ("p_tpitch", "Pitch", 1), ("p_trev", "Reverse", 1), ("p_tprob", "Prob", 0),
               ("p_trange", "Range", 0), ("p_twidth", "Width", 0), ("p_trept", "Repeat", 0), ("p_tchaos", "Chaos", 0)]
GEN_DEFAULTS = {d[0]: d[5] for pg in DIALS.values() for d in pg if d[0].startswith("p_")}
GEN_RANGES = {d[0]: (d[3], d[4]) for pg in DIALS.values() for d in pg if d[0].startswith("p_")}

# --------------------------------------------------------------------------- the GenExpr engine
def genexpr():
    P = []
    P += [("p_bufsec",), ]
    out = ["// MMM Vocal Chopper engine: rolling record buffer -> grain pool -> 4 stereo voices.",
           "// Generated by build_chopper.py - edit there, not here.",
           "// in1/in2 = live input; out1..out8 = voice1 L/R, voice2 L/R, voice3 L/R, voice4 L/R (dry is added to voice 1).",
           "// Counters p_tick / p_fire / p_panic: any change = one event (set by Max, no sample-accurate clock needed)."]
    for n, (lo, hi) in GEN_RANGES.items():
        out.append(f"Param {n}({GEN_DEFAULTS[n]}, min={lo}, max={hi});")
    out += [
        "Param p_hold(0, min=0, max=1);",
        "Param p_trigmode(0, min=0, max=2);      // 0 clock, 1 onset, 2 both",
        "Param p_outs(4, min=1, max=4);",
        "Param p_route(0, min=0, max=3);         // 0 random, 1 cycle, 2 by level, 3 by pitch",
        "Param p_tick(0, min=0, max=1000000000);",
        "Param p_fire(0, min=0, max=1000000000);",
        "Param p_panic(0, min=0, max=1000000000);",
        "Param p_lfo(0, min=0, max=1);",
        "Param p_lfotick(0, min=0, max=1);       // 1 = new S&H values on every chop step instead of the LFO clock",
    ]
    for n, _, d in LFO_TARGETS:
        out.append(f"Param {n}({d}, min=0, max=1);")
    out.append(f"Data bufL({BUF}); Data bufR({BUF});")
    out.append("History wr(0); History ef(0); History es(0); History gapc(0);")
    out.append("History prevtick(0); History prevfire(0); History prevpanic(0);")
    out.append("History repleft(0); History repcnt(0); History rr(0);")
    out.append("History lph(0);")
    out.append("History s_dur(1000); History s_start(0); History s_inc(1); History s_lg(1); History s_rg(1); History s_voice(0); History s_fade(100);")
    for i in range(1, 9):
        out.append(f"History sh{i}(0); History l{i}(0);")
    for g in range(NG):
        out.append(f"History g{g}act(0); History g{g}pos(0); History g{g}inc(1); History g{g}age(0); History g{g}len(1000); "
                   f"History g{g}fade(100); History g{g}lg(1); History g{g}rg(1); History g{g}v(0);")

    locals_ = ("inL inR m bl hd a ca cr cs thrl onset tk fi pn clkon lt lclk tau lf ev newg r sz dur semi inc dr span maxback bk far "
               "lv pn2 ang nv v u uu db pr slot best rm fd ee eo pw i0 i1 fr sa sb gl gr vv dry "
               "size_e pitch_e rev_e prob_e range_e width_e rept_e chaos_e o1 o2 o3 o4 o5 o6 o7 o8").split()
    out.append("")
    out.append("// ---- locals (all initialised) ----")
    out.append(" ".join(f"{n} = 0;" for n in locals_))
    out.append("""
inL = in1; inR = in2;
m = 0.5 * (inL + inR);
bl = floor(min(%d, max(1000, p_bufsec * samplerate)));
dry = max(0, min(1, p_dry));

// ---- record (hold = freeze the buffer) ----
hd = p_hold;
if (hd < 0.5) {
    poke(bufL, inL, wr);
    poke(bufR, inR, wr);
    wr = wr + 1;
    if (wr >= bl) { wr = 0; }
}
if (wr >= bl) { wr = 0; }

// ---- onset detector: fast envelope vs slow envelope, threshold + refractory gap ----
a = abs(m);
ca = 1 - exp(-1 / (0.001 * samplerate));
cr = 1 - exp(-1 / (0.03 * samplerate));
cs = 1 - exp(-1 / (0.25 * samplerate));
if (a > ef) { ef = ef + (a - ef) * ca; }
if (a <= ef) { ef = ef + (a - ef) * cr; }
es = es + (a - es) * cs;
thrl = pow(10, p_thr / 20);
if (gapc > 0) { gapc = gapc - 1; }
onset = 0;
if (p_trigmode > 0.5) {
    if (ef > thrl) {
        if (ef > es * p_sens) {
            if (gapc <= 0) { onset = 1; gapc = p_gap * 0.001 * samplerate; }
        }
    }
}

// ---- counters from Max ----
tk = 0; if (p_tick != prevtick) { tk = 1; } prevtick = p_tick;
fi = 0; if (p_fire != prevfire) { fi = 1; } prevfire = p_fire;
pn = 0; if (p_panic != prevpanic) { pn = 1; } prevpanic = p_panic;
clkon = 1;
if (p_trigmode > 0.5) { if (p_trigmode < 1.5) { clkon = 0; } }

// ---- sample & hold LFO: 8 independent values, smoothed by Slew ----
lph = lph + max(0.05, p_lfor) / samplerate;
lt = 0;
if (lph >= 1) { lph = lph - 1; lt = 1; }
lclk = lt;
if (p_lfotick > 0.5) { lclk = tk; }
if (lclk > 0.5) {
    sh1 = noise(); sh2 = noise(); sh3 = noise(); sh4 = noise(); sh5 = noise(); sh6 = noise(); sh7 = noise(); sh8 = noise();
}
tau = max(1, p_lfoslew * 0.001 * samplerate);
l1 = l1 + (sh1 - l1) / tau; l2 = l2 + (sh2 - l2) / tau; l3 = l3 + (sh3 - l3) / tau; l4 = l4 + (sh4 - l4) / tau;
l5 = l5 + (sh5 - l5) / tau; l6 = l6 + (sh6 - l6) / tau; l7 = l7 + (sh7 - l7) / tau; l8 = l8 + (sh8 - l8) / tau;
lf = 0;
if (p_lfo > 0.5) { lf = max(0, min(1, p_lfodepth)); }

// ---- event: clock tick, onset or Fire button ----
ev = fi;
if (onset > 0.5) { ev = 1; }
if (tk > 0.5) { if (clkon > 0.5) { ev = 1; } }
newg = 0;
if (ev > 0.5) {
    size_e = p_size * pow(2, lf * p_tsize * l1 * 2);
    pitch_e = min(24, max(0, p_pitch + lf * p_tpitch * l2 * 12));
    rev_e = min(1, max(0, p_rev + lf * p_trev * l3 * 0.5));
    prob_e = min(1, max(0, p_prob + lf * p_tprob * l4 * 0.5));
    range_e = min(1, max(0.02, p_range + lf * p_trange * l5 * 0.5));
    width_e = min(1, max(0, p_width + lf * p_twidth * l6 * 0.5));
    rept_e = min(8, max(1, p_rept + lf * p_trept * l7 * 3));
    chaos_e = min(1, max(0, p_chaos + lf * p_tchaos * l8 * 0.5));
    r = (noise() + 1) * 0.5;
    if (fi > 0.5) { r = 0; }
    if (r <= prob_e) {
        // length: Size, spread by Chaos (up to +-1.5 octaves)
        sz = size_e * pow(2, noise() * chaos_e * 1.5);
        sz = max(10, min(3000, sz));
        dur = sz * 0.001 * samplerate;
        // pitch scatter in whole semitones, reverse
        semi = floor(noise() * pitch_e * chaos_e + 0.5);
        inc = pow(2, semi / 12);
        dr = 1;
        u = (noise() + 1) * 0.5;
        if (u < rev_e * chaos_e) { dr = -1; }
        dur = min(dur, (bl - 2000) / inc);
        span = dur * inc;
        // position: somewhere inside the last Range * buffer, never past the write head
        maxback = max(0, range_e * bl - span);
        bk = (noise() + 1) * 0.5 * maxback;
        far = bk + span;
        s_start = wr - far;
        if (dr < 0) { s_start = wr - bk; }
        s_inc = inc * dr;
        s_dur = dur;
        s_fade = max(8, min(dur * 0.5, p_fade * 0.001 * samplerate));
        // level + pan (equal power)
        lv = 1 - (noise() + 1) * 0.5 * p_lvlvar * chaos_e;
        pn2 = noise() * width_e;
        ang = (pn2 * 0.5 + 0.5) * 1.5707963;
        s_lg = cos(ang) * 1.41421 * lv;
        s_rg = sin(ang) * 1.41421 * lv;
        // which of the 4 outs
        nv = max(1, min(4, floor(p_outs + 0.5)));
        v = 0;
        u = (noise() + 1) * 0.5;
        if (p_route < 0.5) { v = floor(u * nv); }
        if (p_route >= 0.5) { if (p_route < 1.5) { rr = rr + 1; if (rr >= nv) { rr = 0; } v = rr; } }
        if (p_route >= 1.5) {
            if (p_route < 2.5) {
                db = 20 * log(ef + 0.000001) / 2.302585;
                uu = max(0, min(0.999, (db + 50) / 45));
                v = floor(uu * nv);
            }
        }
        if (p_route >= 2.5) {
            pr = max(1, pitch_e * chaos_e);
            uu = max(0, min(0.999, (semi / pr) * 0.5 + 0.5));
            v = floor(uu * nv);
        }
        s_voice = min(v, nv - 1);
        repleft = floor(rept_e + 0.5) - 1;
        repcnt = dur;
        newg = 1;
    }
}
// repeats (stutter): same slice again, back to back
if (newg < 0.5) {
    if (repleft > 0.5) {
        repcnt = repcnt - 1;
        if (repcnt <= 0) { newg = 1; repleft = repleft - 1; repcnt = s_dur; }
    }
}

// ---- panic: stop everything ----
if (pn > 0.5) {
    repleft = 0; newg = 0;
%s}

// ---- allocate a grain: lowest free slot, else steal the one closest to its end ----
if (newg > 0.5) {
    slot = -1;
%s    if (slot < 0) {
        best = 1000000000;
%s    }
%s}
""" % (BUF,
       "".join(f"    g{g}act = 0;\n" for g in range(NG)),
       "".join(f"    if (g{g}act < 0.5) {{ slot = {g}; }}\n" for g in reversed(range(NG))),
       "".join(f"        rm = g{g}len - g{g}age; if (rm < best) {{ best = rm; slot = {g}; }}\n" for g in range(NG)),
       "".join(f"    if (slot == {g}) {{ g{g}pos = s_start; g{g}inc = s_inc; g{g}age = 0; g{g}len = s_dur; g{g}fade = s_fade; "
               f"g{g}lg = s_lg; g{g}rg = s_rg; g{g}v = s_voice; g{g}act = 1; }}\n" for g in range(NG))))

    out.append("// ---- grains: linear interpolation, smoothstep fade in/out ----")
    for g in range(NG):
        out.append(f"""if (g{g}act > 0.5) {{
    fd = g{g}fade;
    ee = g{g}age / fd; if (ee > 1) {{ ee = 1; }}
    eo = (g{g}len - g{g}age) / fd; if (eo > 1) {{ eo = 1; }}
    if (eo < ee) {{ ee = eo; }}
    if (ee < 0) {{ ee = 0; }}
    ee = ee * ee * (3 - 2 * ee);
    pw = g{g}pos; pw = pw - bl * floor(pw / bl);
    i0 = floor(pw); fr = pw - i0; i1 = i0 + 1; if (i1 >= bl) {{ i1 = 0; }}
    sa = peek(bufL, i0); sa = sa + (peek(bufL, i1) - sa) * fr;
    sb = peek(bufR, i0); sb = sb + (peek(bufR, i1) - sb) * fr;
    gl = sa * ee * g{g}lg; gr = sb * ee * g{g}rg;
    vv = g{g}v;
    if (vv < 0.5) {{ o1 = o1 + gl; o2 = o2 + gr; }}
    if (vv > 0.5) {{ if (vv < 1.5) {{ o3 = o3 + gl; o4 = o4 + gr; }} }}
    if (vv > 1.5) {{ if (vv < 2.5) {{ o5 = o5 + gl; o6 = o6 + gr; }} }}
    if (vv > 2.5) {{ o7 = o7 + gl; o8 = o8 + gr; }}
    g{g}pos = g{g}pos + g{g}inc;
    g{g}age = g{g}age + 1;
    if (g{g}age >= g{g}len) {{ g{g}act = 0; }}
}}""")
    out.append("""
out1 = o1 + inL * dry; out2 = o2 + inR * dry;
out3 = o3; out4 = o4; out5 = o5; out6 = o6; out7 = o7; out8 = o8;
""")
    return "\n".join(out)

