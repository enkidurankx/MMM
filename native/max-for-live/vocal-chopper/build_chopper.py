class Patch:
    def __init__(self):
        self.boxes, self.lines, self.n, self.vars = [], [], 0, {}
        self.cx, self.cy = 30, 400   # patching-view cursor (layout only, no meaning)

    def _id(self):
        self.n += 1
        return f"obj-{self.n}"

    def add(self, **kw):
        i = self._id()
        if "patching_rect" not in kw:
            kw["patching_rect"] = [float(self.cx), float(self.cy), 120.0, 22.0]
            self.cy += 28
            if self.cy > 1100:
                self.cy, self.cx = 400, self.cx + 170
        self.boxes.append({"box": dict(id=i, **kw)})
        return i

    def obj(self, text, nin, nout, outtypes=None, **kw):
        return self.add(maxclass="newobj", text=text, numinlets=nin, numoutlets=nout, outlettype=outtypes or [""] * nout, **kw)

    def msg(self, text, **kw):
        return self.add(maxclass="message", text=text, numinlets=2, numoutlets=1, outlettype=[""], **kw)

    def line(self, a, ao, b, bi):
        self.lines.append({"patchline": {"destination": [b, bi], "source": [a, ao]}})

    # ---- live.* controls (presentation)
    def _pres(self, kw, rect, page=None, hidden=False):
        kw.update(presentation=1, presentation_rect=[float(v) for v in rect])
        if hidden:
            kw["hidden"] = 1

    def dial(self, d, rect, page=None, hidden=False):
        name, longn, short, mn, mx, init, unit, typ, exp = d
        kw = dict(maxclass="live.dial", numinlets=1, numoutlets=2, outlettype=["", "float"], parameter_enable=1,
                  varname=longn.replace(" ", "_"), fontsize=9.0,
                  saved_attribute_attributes={"valueof": {"parameter_initial": [init], "parameter_initial_enable": 1,
                      "parameter_longname": longn, "parameter_mmax": float(mx), "parameter_mmin": float(mn),
                      "parameter_shortname": short, "parameter_type": typ, "parameter_unitstyle": unit,
                      "parameter_exponent": exp}})
        self._pres(kw, rect, page, hidden)
        i = self.add(**kw)
        self.vars[i] = (kw["varname"], page)
        return i

    def enum(self, cls, longn, short, items, init, rect, page=None, hidden=False, **extra):
        kw = dict(maxclass=cls, numinlets=1, numoutlets=3, outlettype=["", "", "float"], parameter_enable=1,
                  varname=longn.replace(" ", "_"), fontsize=9.0,
                  saved_attribute_attributes={"valueof": {"parameter_enum": items, "parameter_initial": [init],
                      "parameter_initial_enable": 1, "parameter_longname": longn, "parameter_mmax": len(items) - 1,
                      "parameter_shortname": short, "parameter_type": 2}})
        kw.update(extra)
        self._pres(kw, rect, page, hidden)
        i = self.add(**kw)
        self.vars[i] = (kw["varname"], page)
        return i

    def text(self, longn, label, init, rect, mode=1, page=None, hidden=False):
        kw = dict(maxclass="live.text", numinlets=1, numoutlets=2, outlettype=["", ""], parameter_enable=1, mode=mode,
                  text=label, texton=label, varname=longn.replace(" ", "_"), fontsize=9.0,
                  saved_attribute_attributes={"valueof": {"parameter_enum": ["off", "on"], "parameter_initial": [init],
                      "parameter_initial_enable": 1, "parameter_longname": longn, "parameter_mmax": 1,
                      "parameter_shortname": label, "parameter_type": 2}})
        self._pres(kw, rect, page, hidden)
        i = self.add(**kw)
        self.vars[i] = (kw["varname"], page)
        return i

    def comment(self, label, rect, page=None, hidden=False, size=9.0, bold=0):
        vn = "lbl_" + label.replace(" ", "_").replace("/", "_").lower() + f"_{self.n + 1}"
        kw = dict(maxclass="comment", text=label, numinlets=1, numoutlets=0, varname=vn, fontsize=size, fontface=bold)
        self._pres(kw, rect, page, hidden)
        i = self.add(**kw)
        self.vars[i] = (vn, page)
        return i

