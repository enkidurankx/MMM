#!/usr/bin/env python3
"""Generates MMM Ring Mod (Max for Live audio effect).

  python3 build_ringmod.py -> MMM_RingMod.genexpr  (the DSP, paste-able into any gen~ codebox)
                              MMM_RingMod.maxpat / .amxd

Same generator style and container as ../vocal-chopper (Param / History / plain if-blocks, locals initialised at the top,
no loops, no ternary): constructs that are proven to run in Live in ../../age12/m4l.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "vocal-chopper"))
from build_chopper import Patch, finish, amxd_bytes   # noqa: E402

# (msg name, longname, short, min, max, init, unitstyle, type 0 float / 1 int, exponent)
# unitstyle: 0 int, 1 float, 2 ms, 3 Hz, 4 dB, 7 semitones
ROW1 = [
    ("p_freq",   "Carrier Freq",  "Freq",   0.1,  8000, 440,  3, 0, 4.0),
    ("p_fine",   "Carrier Fine",  "Fine",  -100,  100,  0,    0, 0, 1.0),
    ("p_pw",     "Carrier Shape", "Shape",  0.05, 0.95, 0.5,  1, 0, 1.0),
    ("p_fold",   "Carrier Fold",  "Fold",   0,    1,    0,    1, 0, 1.0),
    ("p_bias",   "Ring to AM",    "Ring>AM", 0,   1,    0,    1, 0, 1.0),
    ("p_fm",     "Input FM",      "In FM",  0,    1,    0,    1, 0, 2.0),
    ("p_spread", "Stereo Spread", "Spread", 0,    0.5,  0,    1, 0, 1.0),
]
ROW2 = [
    ("p_lfor",   "LFO Rate",      "LFO Hz", 0.02, 30,   1,    3, 0, 3.0),
    ("p_lfod",   "LFO Depth",     "LFO Oct", 0,   2,    0,    1, 0, 2.0),
    ("p_drive",  "Input Drive",   "Drive",  0,    1,    0,    1, 0, 1.0),
    ("p_hp",     "Output HP",     "HP",     20,   2000, 20,   3, 0, 3.0),
    ("p_lp",     "Output LP",     "LP",     200,  20000, 20000, 3, 0, 3.0),
    ("p_wet",    "Dry Wet",       "Wet",    0,    1,    1,    1, 0, 1.0),
    ("p_gain",   "Output Gain",   "Out dB", -24,  12,   0,    4, 0, 1.0),
]
ENUMS = [("p_wave", "Wave", "Wave", ["Sine", "Tri", "Square", "Saw"], 0),
         ("p_mode", "Mode", "Mode", ["Ideal", "Diode"], 0)]
DIALS = ROW1 + ROW2
DEFAULTS = {d[0]: d[5] for d in DIALS}
DEFAULTS.update({e[0]: e[4] for e in ENUMS})

def channel(ch, other_phase_off):
    """GenExpr for one channel. ch = 'L' or 'R'; R carrier is offset by Spread (phase, in cycles)."""
    s = ch
    return f"""
// ---- channel {ch}
x{s} = in{'1' if ch == 'L' else '2'} * ingain;
x{s} = x{s} + drv * (tanh_{s}(x{s} * 3) - x{s});
pp{s} = ph{'' if ch == 'L' else ' + p_spread'};
pp{s} = pp{s} - floor(pp{s});
dt{s} = min(0.45, fhz / samplerate);
// carrier
c{s} = 0;
if (p_wave < 0.5) {{ c{s} = sin(6.2831853 * pp{s}); }}
if (p_wave > 0.5) {{
  if (p_wave < 1.5) {{
    c{s} = 4 * abs(pp{s} - 0.5) - 1;
    c{s} = 0 - c{s};
  }}
}}
if (p_wave > 1.5) {{
  if (p_wave < 2.5) {{
    c{s} = 1;
    if (pp{s} >= p_pw) {{ c{s} = -1; }}
    bl{s} = 0;
    if (pp{s} < dt{s}) {{ u = pp{s} / dt{s}; bl{s} = u + u - u * u - 1; }}
    if (pp{s} > 1 - dt{s}) {{ u = (pp{s} - 1) / dt{s}; bl{s} = u * u + u + u + 1; }}
    c{s} = c{s} + bl{s};
    q{s} = pp{s} - p_pw;
    q{s} = q{s} - floor(q{s});
    bl{s} = 0;
    if (q{s} < dt{s}) {{ u = q{s} / dt{s}; bl{s} = u + u - u * u - 1; }}
    if (q{s} > 1 - dt{s}) {{ u = (q{s} - 1) / dt{s}; bl{s} = u * u + u + u + 1; }}
    c{s} = c{s} - bl{s};
  }}
}}
if (p_wave > 2.5) {{
  c{s} = 2 * pp{s} - 1;
  bl{s} = 0;
  if (pp{s} < dt{s}) {{ u = pp{s} / dt{s}; bl{s} = u + u - u * u - 1; }}
  if (pp{s} > 1 - dt{s}) {{ u = (pp{s} - 1) / dt{s}; bl{s} = u * u + u + u + 1; }}
  c{s} = c{s} - bl{s};
}}
// fold (smooth wavefolder) + AM bias
c{s} = c{s} + p_fold * (sin(1.5707963 * c{s} * (1 + p_fold * 5)) - c{s});
ce{s} = c{s} + p_bias * ((0.5 + 0.5 * c{s}) - c{s});
// modulation
r{s} = x{s} * ce{s};
if (p_mode > 0.5) {{
  k{s} = c{s};
  r{s} = k{s} / (abs(k{s}) + 0.05);
  r{s} = r{s} * (dio(k{s} + x{s}) - dio(k{s} - x{s})) * 0.5;
  r{s} = r{s} + p_bias * (x{s} * ce{s} - r{s});
}}
// output filters (one pole HP / LP) + wet/dry + gain
lp{s} = lp{s} + (r{s} - lp{s}) * alp;
hl{s} = hl{s} + (lp{s} - hl{s}) * ahp;
y{s} = lp{s} - hl{s};
o{s} = (in{'1' if ch == 'L' else '2'} * (1 - p_wet) + y{s} * p_wet) * og;
"""

def genexpr():
    P = [("p_freq", 440, 0.1, 8000), ("p_fine", 0, -100, 100), ("p_pw", 0.5, 0.05, 0.95), ("p_fold", 0, 0, 1),
         ("p_bias", 0, 0, 1), ("p_fm", 0, 0, 1), ("p_spread", 0, 0, 0.5), ("p_lfor", 1, 0.02, 30), ("p_lfod", 0, 0, 2),
         ("p_drive", 0, 0, 1), ("p_hp", 20, 20, 2000), ("p_lp", 20000, 200, 20000), ("p_wet", 1, 0, 1),
         ("p_gain", 0, -24, 12), ("p_wave", 0, 0, 3), ("p_mode", 0, 0, 1)]
    out = ["// MMM Ring Mod: flexible stereo ring / amplitude modulator.",
           "// Carrier: sine / tri / square (pulse width) / saw (PolyBLEP), wavefolder, fine tune, LFO on pitch, input->carrier FM,",
           "// Ring <-> AM bias, ideal or diode-bridge character, stereo phase spread, drive, output HP/LP, wet/dry.",
           "// Generated by build_ringmod.py - edit there, not here.",
           "// in1/in2 = audio in; out1/out2 = audio out."]
    for n, d, a, b in P:
        out.append(f"Param {n}({d}, min={a}, max={b});")
    out += ["History ph(0); History lph(0); History lpL(0); History hlL(0); History lpR(0); History hlR(0);",
            "",
            "// ---- locals (all initialised) ----",
            "xL = 0; xR = 0; ppL = 0; ppR = 0; dtL = 0; dtR = 0; cL = 0; cR = 0; blL = 0; blR = 0; qL = 0; qR = 0; ceL = 0; ceR = 0; "
            "rL = 0; rR = 0; kL = 0; kR = 0; yL = 0; yR = 0; oL = 0; oR = 0; u = 0; m = 0; fhz = 0; lfo = 0; ingain = 1; drv = 0; "
            "alp = 0; ahp = 0; og = 1; v = 0; w = 0; dd = 0; dA = 0; dB = 0; t1 = 0; t2 = 0;",
            "",
            "ingain = 1 + p_drive * 3;",
            "drv = p_drive;",
            "m = 0.5 * (in1 + in2);",
            "// carrier frequency: Hz * fine tune * LFO (octaves) * input FM (up to +-2 octaves)",
            "lph = lph + p_lfor / samplerate;",
            "lph = lph - floor(lph);",
            "lfo = sin(6.2831853 * lph);",
            "m = max(-1, min(1, m));",
            "fhz = p_freq * pow(2, p_fine / 1200 + lfo * p_lfod + m * p_fm * p_fm * 2);",
            "fhz = max(0.01, min(0.45 * samplerate, fhz));",
            "ph = ph + fhz / samplerate;",
            "ph = ph - floor(ph);",
            "alp = 1 - exp(0 - 6.2831853 * min(0.45 * samplerate, p_lp) / samplerate);",
            "ahp = 1 - exp(0 - 6.2831853 * p_hp / samplerate);",
            "og = pow(10, p_gain / 20);"]
    body = channel("L", 0) + channel("R", 1)
    # helper "functions" the style rules avoid: expand tanh_X(...) and dio(...) inline via local-variable macros
    body = _inline(body)
    out.append(body)
    out.append("out1 = oL; out2 = oR;")
    return "\n".join(out)

def _inline(code):
    """The chopper style avoids user functions; tanh and the diode curve are expanded by this tiny macro pass."""
    import re
    def tanh(m):
        a = m.group(1)
        e = f"exp(2 * max(-20, min(20, {a})))"
        return f"(({e} - 1) / ({e} + 1))"
    code = re.sub(r"tanh_[LR]\(((?:[^()]|\([^()]*\))*)\)", tanh, code)
    # diode curve D(z): dead zone vb=0.2, quadratic to vl=0.4, then linear; odd. Written with min/max so no branches:
    #   a = |z|;  lo = max(0, min(a, 0.4) - 0.2);  D = sign(z) * ( lo*lo/0.4 + max(0, a - 0.4) )
    def dio(m):
        z = m.group(1)
        a = f"abs({z})"
        sg = f"(({z}) / (abs({z}) + 0.000001))"
        return f"({sg} * (pow(max(0, min({a}, 0.4) - 0.2), 2) / 0.4 + max(0, {a} - 0.4)))"
    # nested parens inside dio(...) args, up to two levels
    pat = r"dio\(((?:[^()]|\((?:[^()]|\([^()]*\))*\))*)\)"
    return re.sub(pat, dio, code)

def build(code):
    p = Patch()
    gin = [dict(id=f"obj-{i}", maxclass="newobj", text=f"in {i}", numinlets=0, numoutlets=1, outlettype=[""],
                patching_rect=[30.0 + 80 * (i - 1), 30.0, 40.0, 22.0]) for i in (1, 2)]
    gcode = dict(id="obj-3", maxclass="codebox", code=code, numinlets=2, numoutlets=2, outlettype=["", ""],
                 patching_rect=[30.0, 80.0, 760.0, 600.0], fontname="Menlo", fontsize=11.0)
    gout = [dict(id=f"obj-{3 + i}", maxclass="newobj", text=f"out {i}", numinlets=1, numoutlets=0,
                 patching_rect=[30.0 + 80 * (i - 1), 720.0, 40.0, 22.0]) for i in (1, 2)]
    glines = [{"patchline": {"destination": ["obj-3", i], "source": [f"obj-{i + 1}", 0]}} for i in range(2)]
    glines += [{"patchline": {"destination": [f"obj-{4 + i}", 0], "source": ["obj-3", i]}} for i in range(2)]
    gen_patcher = {"fileversion": 1, "appversion": {"major": 8, "minor": 6, "revision": 2, "architecture": "x64", "modernui": 1},
                   "classnamespace": "dsp.gen", "rect": [100.0, 100.0, 840.0, 780.0], "bglocked": 0, "openinpresentation": 0,
                   "default_fontsize": 12.0, "default_fontface": 0, "default_fontname": "Arial", "gridonopen": 1,
                   "gridsize": [15.0, 15.0], "gridsnaponopen": 1, "objectsnaponopen": 1, "statusbarvisible": 2,
                   "toolbarvisible": 1, "lefttoolbarpinned": 0, "toptoolbarpinned": 0, "righttoolbarpinned": 0,
                   "bottomtoolbarpinned": 0, "toolbars_unpinned_last_save": 0, "tallnewobj": 0, "boxanimatetime": 200,
                   "enablehscroll": 1, "enablevscroll": 1, "devicewidth": 0.0, "description": "", "digest": "", "tags": "",
                   "style": "", "subpatcher_template": "", "assistshowspatchername": 0,
                   "boxes": [{"box": b} for b in gin + [gcode] + gout], "lines": glines}
    plugin = p.obj("plugin~", 2, 2, ["signal", "signal"])
    gen = p.add(maxclass="newobj", text="gen~", numinlets=2, numoutlets=2, outlettype=["signal", "signal"], patcher=gen_patcher)
    plugout = p.obj("plugout~", 2, 0)
    for i in range(2):
        p.line(plugin, i, gen, i)
        p.line(gen, i, plugout, i)
    def to_gen(src, name):
        pp = p.obj(f"prepend {name}", 1, 1)
        p.line(src, 0, pp, 0)
        p.line(pp, 0, gen, 0)
    p.comment("MMM RING MOD", [6, 6, 120, 14], size=10.0, bold=1)
    wv = p.enum("live.tab", "Wave", "Wave", ENUMS[0][3], 0, [140, 5, 190, 18])
    md = p.enum("live.tab", "Mode", "Mode", ENUMS[1][3], 0, [340, 5, 110, 18])
    to_gen(wv, "p_wave")
    to_gen(md, "p_mode")
    for row, y in ((ROW1, 30), (ROW2, 94)):
        for i, d in enumerate(row):
            dl = p.dial(d, [6 + i * 64, y, 58, 60])
            to_gen(dl, d[0])
    return finish(p.boxes, p.lines, 460.0, "MMM Ring Mod: flexible ring / amplitude modulator with waveforms, fold, FM, LFO, diode mode")

if __name__ == "__main__":
    os.chdir(HERE)
    code = genexpr()
    open("MMM_RingMod.genexpr", "w").write(code + "\n")
    doc = build(code)
    open("MMM_RingMod.maxpat", "w").write(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    open("MMM_RingMod.amxd", "wb").write(amxd_bytes(doc))
    print("wrote MMM_RingMod.{genexpr,maxpat,amxd}")
